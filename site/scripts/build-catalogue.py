"""Builds the archive and the floating-ink stickers from the curated Instagram downloads.

    python -I scripts/build-catalogue.py <raw_dir> <ink_dir>

raw_dir: full/f_NNN_<key>.jpg (feed photos), sheets/index.json (n → key, timestamp)
ink_dir: full/f_NNN_<key>.webp and mix/m_XX.webp (outputs of extract-ink.py)
Writes public/works/aNNN.webp (1080 px) + aNNN_s.webp (480 px wide), public/ink/*.webp (≤ 560 px)
and src/catalogue.js. Styles and sticker picks live in scripts/catalogue-styles.txt.
Last, lift-redraws.py replaces each sticker that has an AI redraw in ../assets/redraws (BRIEF.md v6).
"""
import sys, os, re, json, datetime, subprocess
import cv2

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
raw, ink = sys.argv[1], sys.argv[2]
STY = {"r": "realismo", "b": "blackwork", "f": "fineline", "l": "lettering", "c": "colore"}
MIX_INK = ["07", "08", "12", "13", "14", "16", "17", "18", "25", "26", "28", "30", "32", "33", "36", "39", "40"]

spec = {}
for line in open(os.path.join(HERE, "catalogue-styles.txt"), encoding="utf8"):
    if line.startswith("#"):
        continue
    for n, s, star in re.findall(r"(\d+):([rbflc])(\*?)", line):
        spec[int(n)] = (STY[s], bool(star))

index = {e["n"]: e for e in json.load(open(os.path.join(raw, "sheets", "index.json"), encoding="utf8"))}
os.makedirs(os.path.join(SITE, "public", "works"), exist_ok=True)
os.makedirs(os.path.join(SITE, "public", "ink"), exist_ok=True)


def padded(st, frac=0.08):
    """transparent margin so the shader's blurred glow never smears an edge pixel"""
    h, w = st.shape[:2]
    m = round(max(h, w) * frac)
    return cv2.copyMakeBorder(st, m, m, m, m, cv2.BORDER_CONSTANT, value=(0, 0, 0, 0))


def fit(im, long_side=None, width=None):
    h, w = im.shape[:2]
    s = (long_side / max(h, w)) if long_side else (width / w)
    return im if s >= 1 else cv2.resize(im, (round(w * s), round(h * s)), interpolation=cv2.INTER_AREA)


feed = []
files = {int(f.split("_")[1]): f for f in os.listdir(os.path.join(raw, "full")) if f.startswith("f_")}
for n, (style, has_ink) in sorted(spec.items()):
    src = files.get(n)
    if not src:
        print("missing photo", n)
        continue
    im = cv2.imread(os.path.join(raw, "full", src), cv2.IMREAD_COLOR)
    fid = f"a{n:03d}"
    cv2.imwrite(os.path.join(SITE, "public", "works", fid + ".webp"), fit(im, long_side=1080), [cv2.IMWRITE_WEBP_QUALITY, 80])
    cv2.imwrite(os.path.join(SITE, "public", "works", fid + "_s.webp"), fit(im, width=480), [cv2.IMWRITE_WEBP_QUALITY, 72])
    if has_ink:
        st = cv2.imread(os.path.join(ink, "full", src.rsplit(".", 1)[0] + ".webp"), cv2.IMREAD_UNCHANGED)
        if st is None:
            print("missing sticker", n)
            has_ink = False
        else:
            cv2.imwrite(os.path.join(SITE, "public", "ink", fid + ".webp"), fit(padded(st), long_side=560), [cv2.IMWRITE_WEBP_QUALITY, 84])
    t = index[n]["t"]
    feed.append({"id": fid, "style": style, "year": datetime.datetime.fromtimestamp(t, datetime.timezone.utc).year, "t": t, "ink": has_ink})

for m in MIX_INK:
    st = cv2.imread(os.path.join(ink, "mix", f"m_{m}.webp"), cv2.IMREAD_UNCHANGED)
    cv2.imwrite(os.path.join(SITE, "public", "ink", f"w{m}.webp"), fit(padded(st), long_side=560), [cv2.IMWRITE_WEBP_QUALITY, 84])

# hero-size variants (≤ 384 px): the hero keeps up to ~90 designs on the GPU at once
os.makedirs(os.path.join(SITE, "public", "ink", "h"), exist_ok=True)
for f in os.listdir(os.path.join(SITE, "public", "ink")):
    if f.endswith(".webp"):
        st = cv2.imread(os.path.join(SITE, "public", "ink", f), cv2.IMREAD_UNCHANGED)
        cv2.imwrite(os.path.join(SITE, "public", "ink", "h", f), fit(st, long_side=384), [cv2.IMWRITE_WEBP_QUALITY, 82])

feed.sort(key=lambda e: -e["t"])
lines = [
    "// GENERATED by scripts/build-catalogue.py — edit scripts/catalogue-styles.txt instead.",
    "// Works from the @sgt.zippo feed (2018–2025), newest first: photo /works/<id>.webp (+ _s),",
    "// floating sticker /ink/<id>.webp when ink is true.",
    "export const FEED = [",
]
lines += [f'  {{ id: "{e["id"]}", style: "{e["style"]}", year: {e["year"]}, ink: {str(e["ink"]).lower()} }},' for e in feed]
lines += ["];", "", "// stickers lifted from the 2026 \"Mix\" reel frames (/ink/w<id>.webp)", f"export const MIX_INK = {json.dumps(MIX_INK)};", ""]
open(os.path.join(SITE, "src", "catalogue.js"), "w", encoding="utf8").write("\n".join(lines))
print(len(feed), "feed works,", sum(e["ink"] for e in feed) + len(MIX_INK), "stickers")
# the floating stickers are the AI redraws where one exists (BRIEF.md v6); this also rebuilds src/ink-aspect.js
subprocess.run([sys.executable, "-I", os.path.join(HERE, "lift-redraws.py")], check=True)
