"""The process act's media (owner, round 8: "for this area use this image turning into this tattoo"): his owl design
(the Procreate file he sent) and the healed owl on the arm (Instagram post DDemBn5IsXA, work a094).

    python -I scripts/owl-process.py

Reads assets/process/owl-design.jpg, assets/process/owl-photo.jpg and the limb mask assets/masks/a094.png. Writes
  public/process/owl.webp          the photo, 960×1200 (the plate is the photo's 4:5 frame)
  public/process/owl_skin.webp     the same arm with no tattoo: skin colour filled in from the bare skin around the ink
  public/process/owl_limb.webp     the limb mask (where the stencil and the needle may go)
  public/process/owl_design.webp   the design, alpha = off the white page
  public/process/owl_lines.webp    its linework: the thin dark strokes, plus the edges of shapes that have no stroke
  src/owl-warp.js                  (generated) a grid over the design and where each vertex lands on the arm
How the design is laid on the photo: a similarity from the two eyes, then normalised cross-correlation of 81 px patches
(blurred, locally normalised luminance) in two passes, fitted with a thin-plate spline after dropping outliers. The
control points are cached in assets/process/owl-ctrl.json (delete it to re-align). Nothing is generated by a model.
"""
import os, json
import numpy as np
import cv2
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__)); SITE = os.path.dirname(HERE); ROOT = os.path.dirname(SITE)
D = cv2.imread(os.path.join(ROOT, "assets", "process", "owl-design.jpg"))
P = cv2.imread(os.path.join(ROOT, "assets", "process", "owl-photo.jpg"))
M = cv2.imread(os.path.join(ROOT, "assets", "masks", "a094.png"), 0)
H, W = P.shape[:2]
DH, DW = D.shape[:2]
CTRL = os.path.join(ROOT, "assets", "process", "owl-ctrl.json")
OUT = os.path.join(SITE, "public", "process")
GRID = (28, 40)  # cells across, down


def U(r):
    with np.errstate(divide="ignore", invalid="ignore"):
        v = r * r * np.log(r)
    return np.nan_to_num(v)


class TPS:
    """thin-plate spline src → dst (coordinates in thousands of px), lam = smoothing"""
    def __init__(self, src, dst, lam):
        n = len(src)
        K = U(np.linalg.norm(src[:, None] - src[None], axis=2)) + lam * np.eye(n)
        Pm = np.c_[np.ones(n), src]
        L = np.zeros((n + 3, n + 3)); L[:n, :n] = K; L[:n, n:] = Pm; L[n:, :n] = Pm.T
        Y = np.zeros((n + 3, 2)); Y[:n] = dst
        self.c = np.linalg.solve(L, Y); self.src = src

    def __call__(self, pts):
        Kq = U(np.linalg.norm(pts[:, None] - self.src[None], axis=2))
        return Kq @ self.c[:-3] + np.c_[np.ones(len(pts)), pts] @ self.c[-3:]


def prep(im):
    g = cv2.GaussianBlur(cv2.cvtColor(im, cv2.COLOR_BGR2GRAY).astype(np.float32), (0, 0), 3.0)
    mu = cv2.GaussianBlur(g, (0, 0), 25); sd = np.sqrt(cv2.GaussianBlur((g - mu) ** 2, (0, 0), 25)) + 6
    return (g - mu) / sd


def match(gD, gP, step, half, search, mask):
    src, dst = [], []
    for y in range(half + search, H - half - search, step):
        for x in range(half + search, W - half - search, step):
            if not mask[y, x] or M[y, x] < 128:
                continue
            t = gD[y - half:y + half + 1, x - half:x + half + 1]
            if t.std() < 0.45:
                continue
            r = gP[y - half - search:y + half + search + 1, x - half - search:x + half + search + 1]
            res = cv2.matchTemplate(r, t, cv2.TM_CCOEFF_NORMED)
            _, mx, _, loc = cv2.minMaxLoc(res)
            r2 = res.copy(); cv2.circle(r2, loc, 6, -1, -1)
            if mx < 0.45 or mx - r2.max() < 0.04:  # weak or ambiguous peak
                continue
            src.append((x, y)); dst.append((x + loc[0] - search, y + loc[1] - search))
    return np.array(src, np.float64), np.array(dst, np.float64)


def robust(src, dst, lam, floor):
    keep = np.ones(len(src), bool)
    for _ in range(4):
        tps = TPS(src[keep] / 1000, dst[keep] / 1000, lam)
        res = np.linalg.norm(tps(src / 1000) * 1000 - dst, axis=1)
        keep = res < max(floor, np.percentile(res[keep], 80) * 1.8)
    return keep


def backward(tps_inv):
    ys, xs = np.mgrid[0:H:8, 0:W:8]
    m = tps_inv(np.c_[xs.ravel(), ys.ravel()].astype(np.float64) / 1000) * 1000
    up = lambda a: cv2.resize(a.reshape(xs.shape).astype(np.float32), (W, H), interpolation=cv2.INTER_LINEAR)
    return up(m[:, 0]), up(m[:, 1])


def align():
    # 1. similarity from the eyes (centres of the yellow irises)
    eD = np.array([[578, 777], [836, 777]], np.float64); eP = np.array([[543, 713], [803, 679]], np.float64)
    va, vb = eD[1] - eD[0], eP[1] - eP[0]
    s = np.linalg.norm(vb) / np.linalg.norm(va); ang = np.arctan2(vb[1], vb[0]) - np.arctan2(va[1], va[0])
    R = s * np.array([[np.cos(ang), -np.sin(ang)], [np.sin(ang), np.cos(ang)]])
    A = np.c_[R, eP[0] - R @ eD[0]]
    Dw = cv2.warpAffine(D, A, (W, H), flags=cv2.INTER_LINEAR, borderValue=(255, 255, 255))
    gP = prep(P)
    content = lambda im: cv2.erode((cv2.cvtColor(im, cv2.COLOR_BGR2GRAY) < 235).astype(np.uint8), np.ones((15, 15), np.uint8))
    # 2. wide search, then a tight one on the spline-warped design
    s1, d1 = match(prep(Dw), gP, 36, 40, 44, content(Dw))
    k1 = robust(s1, d1, 2e-3, 4.0)
    mx, my = backward(TPS(d1[k1] / 1000, s1[k1] / 1000, 2e-3))
    Dt = cv2.remap(Dw, mx, my, cv2.INTER_LINEAR, borderValue=(255, 255, 255))
    s2, d2 = match(prep(Dt), gP, 28, 32, 18, content(Dt))
    s2 = np.c_[mx[s2[:, 1].astype(int), s2[:, 0].astype(int)], my[s2[:, 1].astype(int), s2[:, 0].astype(int)]]
    S, Dd = np.r_[s1[k1], s2], np.r_[d1[k1], d2]
    k2 = robust(S, Dd, 1e-3, 3.0)
    Ai = cv2.invertAffineTransform(A)
    orig = (Ai[:, :2] @ S[k2].T).T + Ai[:, 2]
    json.dump({"design": orig.round(2).tolist(), "photo": Dd[k2].round(2).tolist()}, open(CTRL, "w"))


if not os.path.exists(CTRL):
    align()
ctrl = json.load(open(CTRL))
cD, cP = np.array(ctrl["design"]), np.array(ctrl["photo"])
fwd = TPS(cD / 1000, cP / 1000, 1e-3)  # design px → photo px

# the warp grid: design uv → plate fraction (the plate is the photo's frame)
cols, rows = GRID
vy, vx = np.mgrid[0:rows + 1, 0:cols + 1]
uv = np.c_[(vx / cols).ravel(), (vy / rows).ravel()]
land = fwd(uv * [DW, DH] / 1000) * 1000 / [W, H]
with open(os.path.join(SITE, "src", "owl-warp.js"), "w", encoding="utf8") as f:
    f.write("// generated by scripts/owl-process.py: where each vertex of a grid over his owl design lands on the arm\n")
    f.write("// (fractions of the plate, which is the photo's 4:5 frame), vertices row by row\n")
    f.write(f"export const OWL_GRID = [{cols}, {rows}];\n")
    f.write(f"export const OWL_DESIGN_ASPECT = {DW / DH:.5f};\n")
    f.write("export const OWL_WARP = [" + ",".join(f"{v:.4f}".rstrip("0").rstrip(".") for v in land.ravel()) + "];\n")

os.makedirs(OUT, exist_ok=True)
SZ = (960, 1200)
save = lambda arr, name, **kw: Image.fromarray(arr).save(os.path.join(OUT, name), **kw)

# the photo
save(cv2.cvtColor(cv2.resize(P, SZ, interpolation=cv2.INTER_AREA), cv2.COLOR_BGR2RGB), "owl.webp", quality=88, method=6)

# the limb
limb = cv2.GaussianBlur(M, (0, 0), 2)
save(cv2.resize(limb, SZ, interpolation=cv2.INTER_AREA), "owl_limb.webp", quality=90, method=6)

# bare skin: pixels that read as skin (light, warm, not the yellow ink), smoothed into the inked areas
lab = cv2.cvtColor(P, cv2.COLOR_BGR2LAB).astype(np.float32)
Ls, As, Bs = lab[..., 0] * 100 / 255, lab[..., 1] - 128, lab[..., 2] - 128
skin = (M > 200) & (Ls > 64) & (Bs < 38) & (np.hypot(As, Bs) > 9)
skin = cv2.erode(skin.astype(np.uint8), np.ones((5, 5), np.uint8)).astype(np.float32)
img = P.astype(np.float32)
out = np.zeros_like(img); wsum = np.zeros(skin.shape, np.float32)
for sig in (60, 160, 420):  # skin tone and the arm's lighting only: fine where bare skin is near, coarser further in
    w = cv2.GaussianBlur(skin, (0, 0), sig)
    num = cv2.GaussianBlur(img * skin[..., None], (0, 0), sig)
    est = num / np.maximum(w, 1e-4)[..., None]
    take = np.clip(w * 6, 0, 1) * (1 - np.clip(wsum, 0, 1))
    out += est * take[..., None]; wsum += take
out = out / np.maximum(wsum, 1e-4)[..., None]
bare = np.clip(out, 0, 255).astype(np.uint8)
bare = np.where((M > 30)[..., None], bare, P)  # outside the limb the shader uses its own darkened room
save(cv2.cvtColor(cv2.resize(bare, (480, 600), interpolation=cv2.INTER_AREA), cv2.COLOR_BGR2RGB), "owl_skin.webp", quality=86, method=6)

# the design (alpha = off the page) and its linework, in the design's own frame
DS = (990, 1400)
d = cv2.resize(D, DS, interpolation=cv2.INTER_AREA)
dark = 1 - d.min(axis=2).astype(np.float32) / 255
alpha = np.clip(dark * 5, 0, 1)
rgba = np.dstack([cv2.cvtColor(d, cv2.COLOR_BGR2RGB), (alpha * 255).astype(np.uint8)])
save(rgba, "owl_design.webp", quality=88, method=6)
g = cv2.cvtColor(d, cv2.COLOR_BGR2GRAY)
strokes = cv2.morphologyEx(g, cv2.MORPH_BLACKHAT, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9)))
strokes = np.clip((strokes.astype(np.float32) - 26) / 50, 0, 1)
edges = cv2.Canny(cv2.GaussianBlur(g, (0, 0), 1.6), 36, 96)
edges[cv2.dilate((strokes > 0.3).astype(np.uint8), np.ones((7, 7), np.uint8)) > 0] = 0  # a stroke's own sides
n, cc, st, _ = cv2.connectedComponentsWithStats((edges > 0).astype(np.uint8), 8)
small = np.isin(cc, np.where(st[:, cv2.CC_STAT_AREA] < 18)[0]); edges[small] = 0  # specks
edges = cv2.GaussianBlur(cv2.dilate(edges, np.ones((2, 2), np.uint8)).astype(np.float32) / 255, (0, 0), 0.6)
lines = np.clip(np.maximum(strokes, edges * 0.9), 0, 1)
save((lines * 255).astype(np.uint8), "owl_lines.webp", quality=90, method=6)

print({"ctrl": len(cD), "grid": GRID, "eye_check": fwd(np.array([[578, 777], [836, 777]]) / 1000).round(4).tolist()})
